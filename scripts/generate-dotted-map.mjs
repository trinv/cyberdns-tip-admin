// One-off dev tool — NOT part of the app build. Precomputes the dotted-map
// world grid (https://github.com/NTag/dotted-map) once, offline, and writes
// it as a static TypeScript data module.
//
// Why precompute instead of calling `new DottedMap(...)` in the browser:
// dotted-map's own README warns grid computation at height/width >= 100 can
// take up to ~30s — far too slow to run on every page load. The DNS Nodes
// map's actual pins (real dns_nodes rows) are still added at runtime in
// DnsNodesView.tsx via the fast `getPin()`/`getSVG()` calls against this
// precomputed grid — only the expensive one-time landmass-grid computation
// is baked in here.
//
// Re-run this (`node scripts/generate-dotted-map.mjs` from the repo root)
// only if you deliberately change the params below (height/grid/projection)
// — otherwise the checked-in output in src/components/DnsNodes/worldDotMap.ts
// never needs to be touched again.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { getMapJSON } from 'dotted-map';

const mapJson = getMapJSON({ height: 60, grid: 'diagonal' });

const outPath = fileURLToPath(new URL('../src/components/DnsNodes/worldDotMap.ts', import.meta.url));
const contents = `// AUTO-GENERATED by scripts/generate-dotted-map.mjs — do not hand-edit.
// Precomputed dotted-map (https://github.com/NTag/dotted-map) world grid —
// see that script's own header comment for why this is checked in instead
// of computed at runtime.
import type { MapData } from 'dotted-map/without-countries';

const worldDotMap: MapData = ${mapJson};

export default worldDotMap;
`;

writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} (${(contents.length / 1024).toFixed(1)} KB)`);
